import Database from 'better-sqlite3';
import { drizzle, type BetterSQLite3Database } from 'drizzle-orm/better-sqlite3';
import { migrate } from 'drizzle-orm/better-sqlite3/migrator';
import { existsSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import * as schema from './schema.js';

export * as schema from './schema.js';

export type HubDatabase = BetterSQLite3Database<typeof schema>;

export const DEFAULT_MIGRATIONS_FOLDER = fileURLToPath(new URL('../../drizzle', import.meta.url));

export interface OpenDatabaseOptions {
  /** Path of the SQLite file, or `:memory:`. */
  path: string;
  /** Folder with the versioned migrations generated by drizzle-kit. */
  migrationsFolder?: string;
  /** Called with the backup path just after a pre-migration copy is made. */
  onBackup?: (backupPath: string) => void;
}

export interface OpenedDatabase {
  db: HubDatabase;
  sqlite: Database.Database;
  /** Path of the pre-migration copy, if one was made. */
  backupPath: string | null;
  close(): void;
}

function pendingMigrations(sqlite: Database.Database, folder: string): number {
  const journal = JSON.parse(readFileSync(`${folder}/meta/_journal.json`, 'utf8')) as {
    entries: { when: number }[];
  };
  const hasTable = sqlite
    .prepare("SELECT 1 FROM sqlite_master WHERE type = 'table' AND name = '__drizzle_migrations'")
    .get();
  if (!hasTable) return journal.entries.length;
  const last = sqlite
    .prepare('SELECT created_at AS at FROM __drizzle_migrations ORDER BY created_at DESC LIMIT 1')
    .get() as { at: number } | undefined;
  if (!last) return journal.entries.length;
  return journal.entries.filter((e) => e.when > last.at).length;
}

/** Timestamp-based backup name, safe on every filesystem. */
function backupName(path: string): string {
  const stamp = new Date().toISOString().replace(/[:.]/g, '-');
  return `${path}.pre-migration-${stamp}.bak`;
}

/**
 * Opens the database in WAL mode and applies pending migrations.
 * Before migrating an existing database, a consistent copy is written next to it.
 */
export function openDatabase(options: OpenDatabaseOptions): OpenedDatabase {
  const folder = options.migrationsFolder ?? DEFAULT_MIGRATIONS_FOLDER;
  const isMemory = options.path === ':memory:';
  const existed = !isMemory && existsSync(options.path);

  const sqlite = new Database(options.path);
  sqlite.pragma('journal_mode = WAL');
  sqlite.pragma('foreign_keys = ON');
  sqlite.pragma('busy_timeout = 5000');

  let backupPath: string | null = null;
  try {
    const pending = pendingMigrations(sqlite, folder);
    if (existed && pending > 0 && hasUserTables(sqlite)) {
      backupPath = backupName(options.path);
      // VACUUM INTO writes a consistent copy that includes WAL content.
      sqlite.prepare('VACUUM INTO ?').run(backupPath);
      options.onBackup?.(backupPath);
    }
    const db = drizzle(sqlite, { schema });
    migrate(db, { migrationsFolder: folder });
    return { db, sqlite, backupPath, close: () => sqlite.close() };
  } catch (error) {
    sqlite.close();
    throw error;
  }
}

function hasUserTables(sqlite: Database.Database): boolean {
  return (
    sqlite
      .prepare(
        "SELECT 1 FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%' LIMIT 1",
      )
      .get() !== undefined
  );
}
